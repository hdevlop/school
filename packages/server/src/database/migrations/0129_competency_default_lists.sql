targets AS (
  SELECT assignment."id" AS assignment_id, year."id" AS year_id, subject."code" AS subject_code, class."name" AS class_name
  FROM "teacher_assignments" assignment
  JOIN "classes" class ON class."id" = assignment."class_id"
  JOIN "subjects" subject ON subject."id" = assignment."subject_id"
  JOIN "academic_years" year ON year."label" = class."academic_year"
  WHERE year."reporting_ends_on" >= CURRENT_DATE
    AND NOT EXISTS (SELECT 1 FROM "competency_domains" domain WHERE domain."teacher_assignment_id" = assignment."id")
),
domains AS (
  INSERT INTO "competency_domains" ("id", "teacher_assignment_id", "academic_year_id", "name", "position")
  SELECT substr(md5(random()::text || target.assignment_id || listed.domain_position::text), 1, 10),
    target.assignment_id, target.year_id, listed.domain_name, listed.domain_position
  FROM targets target
  JOIN (SELECT DISTINCT subject_code, class_name, domain_position, domain_name FROM defaults) listed
    ON listed.subject_code = target.subject_code AND listed.class_name = target.class_name
  RETURNING "id", "teacher_assignment_id", "position"
)
INSERT INTO "competencies" ("id", "domain_id", "name", "position")
SELECT substr(md5(random()::text || domain."id" || item.item_position::text), 1, 10), domain."id", item.item_name, item.item_position
FROM domains domain
JOIN targets target ON target.assignment_id = domain."teacher_assignment_id"
JOIN defaults item ON item.subject_code = target.subject_code AND item.class_name = target.class_name
  AND item.domain_position = domain."position";
