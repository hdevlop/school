import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
import postgres from 'postgres';

const base = 'http://localhost:3103';
const target = new URL(process.env.DB_URL);
if (!['localhost','127.0.0.1'].includes(target.hostname)) throw new Error('Local fixture only');
target.pathname = '/school_landing_demo';
const sql = postgres(target.toString());
const browser = await chromium.launch({ channel:'chrome', headless:true });
const context = await browser.newContext({viewport:{width:1440,height:1000}});
await context.addCookies([{name:'school-ui-language',value:'en',url:base}]);
const page = await context.newPage();
const name = `Landing acceptance ${Date.now()}`;
const results = {};
try {
  await page.goto(`${base}/welcome`, {waitUntil:'networkidle'});
  await page.locator('input[name="parentName"]').fill(name);
  await page.locator('input[type="tel"]').press('End');
  await page.locator('input[type="tel"]').pressSequentially('612345678');
  await page.locator('input[name="email"]').fill('visitor@landing.example.test');
  await page.locator('textarea[name="message"]').fill('Please arrange a school visit.');
  console.log('form', await page.locator('form').innerText(), await page.locator('input[type="tel"]').inputValue());
  const submitted = page.waitForResponse(r=>r.url().endsWith('/api/visit-requests') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Send request',exact:true}).click();
  await page.waitForTimeout(1000);
  console.log('after', await page.locator('form').count() ? await page.locator('form').innerText() : await page.getByRole('status').allTextContents());
  results.submission = (await submitted).status();
  await page.getByRole('status').filter({hasText:'Thank'}).waitFor();
  const [visit] = await sql`select id,language,status from visit_requests where parent_name=${name}`;
  if (!visit) throw new Error('Browser submission did not persist');
  results.persisted = visit;
  const notifications = await sql`select recipient_user_id from notifications where source_key=${`visit-request:${visit.id}`}`;
  results.notifications = notifications.length;
  if (!notifications.length) throw new Error('No staff notification');
  await page.goto(`${base}/login`);
  await page.locator('input[name="identifier"]').fill('admin@landing.example.test');
  await page.locator('input[name="password"]').fill('LandingDemo2026!');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await page.waitForURL(url=>!url.pathname.startsWith('/login'));
  await page.goto(`${base}/public-page`,{waitUntil:'networkidle',timeout:120000});
  await page.getByRole('tab',{name:'Programs',exact:true}).click();
  results.programEditor = await page.locator('select').count();
  await page.getByRole('tab',{name:'Photos',exact:true}).click();
  await page.locator('[data-najm-theme-section="branding"]').waitFor();
  console.log('photos', await page.locator('[data-najm-theme-section="branding"]').innerText());
  results.photoInputs = await page.locator('input[type=file]').count();
  const upload = page.waitForResponse(r=>r.url().includes('/api/branding/assets/landingHero/') && r.request().method()==='POST');
  await page.locator('[data-slot="landingHero"] input[type=file]').setInputFiles('apps/dashboard/public/images/landing/program-default.webp');
  results.heroUpload = (await upload).status();
  console.log('branding actions',await page.locator('[data-najm-theme-actions]').innerText());
  const brandingSave = page.waitForResponse(r=>r.url().endsWith('/api/branding') && r.request().method()==='PUT',{timeout:90000});
  await page.locator('[data-najm-theme-actions]').getByRole('button',{name:/Save/}).click();
  results.brandingSave = (await brandingSave).status();
  const publicContext = await browser.newContext();
  const publicPage = await publicContext.newPage();
  await publicPage.goto(`${base}/welcome`, {waitUntil:'networkidle'});
  const hero = publicPage.locator('.landing-hero .landing-photo img');
  await hero.waitFor();
  results.managedHero = await hero.getAttribute('src');
  if (!results.managedHero.includes('branding%2Fassets')) throw new Error('Public hero must use managed optimized asset');
  await publicPage.screenshot({path:'docs/evidence/landing/managed-hero.png'});
  await publicContext.close();
  await page.goto(`${base}/public-page`,{waitUntil:'networkidle'});
  await page.getByRole('tab',{name:'Photos',exact:true}).click();
  await page.locator('[data-slot="landingHero"]').getByRole('button',{name:/Remove|Clear/}).click();
  const restored = page.waitForResponse(r=>r.url().endsWith('/api/branding') && r.request().method()==='PUT',{timeout:90000});
  await page.locator('[data-najm-theme-actions]').getByRole('button',{name:/Save/}).click();
  results.brandingRestore = (await restored).status();
  await page.getByRole('tab',{name:'Publish',exact:true}).click();
  const saved = page.waitForResponse(r=>r.url().endsWith('/api/landing/content') && r.request().method()==='PUT');
  await page.getByRole('button',{name:'Save content',exact:true}).click();
  results.editorSave = (await saved).status();
  await page.goto(`${base}/visit-requests`,{waitUntil:'networkidle',timeout:120000});
  console.log((await page.locator('body').innerText()).slice(-3500));
  await page.getByRole('row').filter({hasText:name}).getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  console.log('dialog',await page.getByRole('dialog').innerText());
  await page.locator('textarea[name="staffNote"]').fill('Called family; visit arranged.');
  await page.getByRole('dialog').locator('select').selectOption('scheduled');
  const updated = page.waitForResponse(r=>r.url().endsWith(`/api/visit-requests/${visit.id}`) && r.request().method()==='PUT');
  await page.getByRole('dialog').getByRole('button',{name:'Save',exact:true}).click();
  results.inboxSave = (await updated).status();
  const [changed] = await sql`select staff_note,handled_by,status from visit_requests where id=${visit.id}`;
  results.staffNote = changed.staff_note;
  results.handledBy = Boolean(changed.handled_by);
  results.updatedStatus = changed.status;
  await page.screenshot({path:'docs/evidence/landing/staff-inbox.png'});
  await page.goto(`${base}/welcome`);
  results.signedInPortal = await page.getByRole('link',{name:'Open dashboard',exact:true}).count();
  await writeFile('docs/evidence/landing/workflow-results.json',JSON.stringify(results,null,2)+'\n');
  console.log(JSON.stringify(results));
} catch (error) {
  console.log('failed page', await page.locator('body').innerText());
  await page.screenshot({path:'docs/evidence/landing/workflow-failure.png'});
  throw error;
} finally {
  const rows = await sql`select id from visit_requests where parent_name=${name}`;
  for (const row of rows) await sql`delete from notifications where source_key=${`visit-request:${row.id}`}`;
  await sql`delete from visit_requests where parent_name=${name}`;
  await sql.end(); await browser.close();
}
